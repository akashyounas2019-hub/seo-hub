/**
 * /admin/build/[id]/pages — list of all pages for one build project.
 *
 * Status badges, AI Overview + SEO scores, "Generate all pending" action,
 * click into per-page editor.
 */
import Link from "next/link";
import { notFound } from "next/navigation";
import { asc, eq } from "drizzle-orm";
import { db, ensureSchema } from "@/db/client";
import { siteBuildPages, siteBuildProjects } from "@/db/schema";
import {
  generateAllPendingPagesAction,
  generatePageAction,
} from "@/app/actions/site-build";
import { Pill, Row, RowList } from "@/components/ui/Row";
import { Pagination, pageParams, paginate, type SearchParams } from "@/components/ui/Pagination";
import { requireAdmin } from "@/lib/server-auth";
import { formatRelative } from "@/lib/utils";

export const dynamic = "force-dynamic";

const STATUS_TONE: Record<string, "info" | "warning" | "success" | "danger" | "neutral"> = {
  pending: "neutral",
  generating: "info",
  ready: "success",
  edited: "warning",
  published: "success",
  failed: "danger",
};

const PAGE_TYPE_LABEL: Record<string, string> = {
  home: "Home",
  service: "Service",
  service_area: "Service area",
  fleet: "Fleet",
  about: "About",
  contact: "Contact",
  blog: "Blog",
  faq: "FAQ",
};

export default async function BuildPagesIndex({
  params,
  searchParams = {},
}: {
  params: { id: string };
  searchParams?: SearchParams;
}) {
  await ensureSchema();
  await requireAdmin();
  const { page: pageNum, perPage } = pageParams(searchParams);

  const [project] = await db()
    .select()
    .from(siteBuildProjects)
    .where(eq(siteBuildProjects.id, params.id))
    .limit(1);
  if (!project) notFound();

  const pages = await db()
    .select()
    .from(siteBuildPages)
    .where(eq(siteBuildPages.projectId, params.id))
    .orderBy(asc(siteBuildPages.sortOrder));

  const pending = pages.filter((p) => p.status === "pending" || p.status === "failed");
  const ready = pages.filter((p) => p.status === "ready" || p.status === "edited");
  const published = pages.filter((p) => p.status === "published");
  const generating = pages.filter((p) => p.status === "generating");

  // Paginate the displayed rows; KPIs + "Generate all pending" stay over the full set.
  const pageRows = paginate(pages, pageNum, perPage);

  return (
    <div className="space-y-6">
      <header className="brand-rule">
        <Link href={`/admin/build/${project.id}`} className="text-xs text-text-faint hover:text-text">
          ← {project.businessName}
        </Link>
        <div className="mt-1 flex items-baseline justify-between gap-3">
          <h1 className="text-2xl font-medium tracking-tightish text-text">Pages</h1>
          {pending.length > 0 ? (
            <form action={generateAllPendingPagesAction}>
              <input type="hidden" name="projectId" value={project.id} />
              <button
                type="submit"
                className="rounded-md bg-accent px-3 py-1.5 text-md font-medium text-accent-fg shadow-xs transition hover:bg-accent-hover"
              >
                Generate all {pending.length} pending →
              </button>
            </form>
          ) : null}
        </div>
        <p className="mt-1.5 text-base text-text-muted">
          Each page is generated by its own Claude job. Pages run in parallel — your Mac worker (or the server daemon) drains them as fast as it can.
        </p>
      </header>

      {/* KPI strip */}
      <section className="grid grid-cols-2 gap-3 sm:grid-cols-4">
        <Kpi label="Total" value={pages.length} />
        <Kpi label="Pending" value={pending.length} tone="neutral" />
        <Kpi label="Generating" value={generating.length} tone="info" />
        <Kpi label="Ready / edited" value={ready.length} tone="success" />
      </section>

      {pages.length === 0 ? (
        <div className="rounded-lg border border-dashed border-border-strong bg-surface px-6 py-12 text-center">
          <p className="text-md font-medium text-text">No pages yet.</p>
          <p className="mt-1 text-base text-text-muted">
            Pages are seeded when the sitemap phase completes. Make sure the sitemap job finished + you approved its phase.
          </p>
        </div>
      ) : (
        <RowList footer={`${pages.length} page${pages.length === 1 ? "" : "s"} · ${published.length} published`}>
          {pageRows.map((p) => (
            <Row key={p.id}>
              <Link href={`/admin/build/${project.id}/pages/${p.id}`} className="flex flex-1 items-center gap-3">
                <Pill tone={STATUS_TONE[p.status] ?? "neutral"}>{p.status}</Pill>
                <span className="font-mono text-xs text-text-faint">{PAGE_TYPE_LABEL[p.pageType] ?? p.pageType}</span>
                <span className="flex-1 truncate text-base text-text">{p.title}</span>
                <span className="font-mono text-xs text-text-faint">{p.pageSlug}</span>
                {p.aiOverviewScore !== null ? (
                  <span title="AI Overview readiness" className="tnum text-xs text-text-muted">
                    AI <strong className="text-text">{p.aiOverviewScore}</strong>
                  </span>
                ) : null}
                {p.seoScore !== null ? (
                  <span title="Technical SEO" className="tnum text-xs text-text-muted">
                    SEO <strong className="text-text">{p.seoScore}</strong>
                  </span>
                ) : null}
                <span className="shrink-0 text-xs text-text-faint">{formatRelative(p.updatedAt)}</span>
              </Link>
              {p.status === "pending" || p.status === "failed" ? (
                <form action={generatePageAction}>
                  <input type="hidden" name="pageId" value={p.id} />
                  <button
                    type="submit"
                    className="ml-2 rounded-md border border-border bg-surface px-2 py-1 text-xs font-medium text-text transition hover:border-accent hover:text-accent"
                  >
                    Generate
                  </button>
                </form>
              ) : null}
            </Row>
          ))}
        </RowList>
      )}

      {pages.length > 0 ? (
        <Pagination
          basePath={`/admin/build/${project.id}/pages`}
          page={pageNum}
          totalItems={pages.length}
          perPage={perPage}
          searchParams={searchParams}
        />
      ) : null}
    </div>
  );
}

function Kpi({
  label,
  value,
  tone,
}: {
  label: string;
  value: number;
  tone?: "success" | "warning" | "info" | "neutral";
}) {
  const color =
    tone === "success"
      ? "text-success"
      : tone === "warning"
        ? "text-warning"
        : tone === "info"
          ? "text-info"
          : tone === "neutral"
            ? "text-text-faint"
            : "text-text";
  return (
    <div
      className="relative overflow-hidden rounded-xl border border-border px-4 py-3"
      style={{ background: "linear-gradient(180deg, var(--surface), var(--surface-2))" }}
    >
      <span
        aria-hidden
        className="pointer-events-none absolute inset-x-3 top-0 h-px"
        style={{ background: "linear-gradient(90deg, transparent, var(--border-strong), transparent)" }}
      />
      <p className="text-xs font-semibold uppercase tracking-[0.10em] text-text-faint">{label}</p>
      <p className={`mt-2 font-semibold tabular-nums text-3xl leading-none tracking-tight ${color}`}>{value}</p>
    </div>
  );
}
